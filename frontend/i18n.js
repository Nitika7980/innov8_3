function setLanguage(lang) {
  if (!SUPPORTED_LANGUAGES[lang]) {
    lang = "en";
  }
  currentLang = lang;
  localStorage.setItem("lexshield_lang", lang);
  
  // Update document language
  document.documentElement.setAttribute("lang", lang);
  
  // Update UI DOM elements
  applyTranslations();

  // If results are actively displayed, re-render them localized
  if (typeof currentAnalysis !== "undefined" && currentAnalysis) {
    if (typeof renderResults === "function") {
      renderResults(currentAnalysis);
    }
  }
  
  // Show toast notification in selected language
  const msg = t("toast_loaded_sample") ? `${SUPPORTED_LANGUAGES[lang].native} (${SUPPORTED_LANGUAGES[lang].name})` : "Language updated";
  if (typeof showToast === "function") {
    showToast(`🌐 Language: ${SUPPORTED_LANGUAGES[lang].flag} ${SUPPORTED_LANGUAGES[lang].native}`);
  }
}

function t(key, fallback = "") {
  const langDict = UI_TRANSLATIONS[currentLang] || UI_TRANSLATIONS["en"];
  if (langDict && langDict[key]) {
    return langDict[key];
  }
  const defaultDict = UI_TRANSLATIONS["en"];
  return (defaultDict && defaultDict[key]) || fallback || key;
}

function getLocalizedRisk(risk, lang = currentLang) {
  if (!risk) return risk;
  const ruleId = risk.rule_id;
  const locData = LOCALIZED_RULES[ruleId] && LOCALIZED_RULES[ruleId][lang];
  
  if (locData) {
    return {
      ...risk,
      title: locData.title || risk.title,
      category: locData.category || risk.category,
      plain_translation: locData.plain || risk.plain_translation,
      why_risky: locData.why || risk.why_risky,
      solution_clause: locData.solution || risk.solution_clause,
      negotiation_tip: locData.script || risk.negotiation_tip
    };
  }
  return risk;
}

